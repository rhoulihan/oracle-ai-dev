-- Volume-scaling sample generator for the measured optimizer. Produces a sized,
-- self-consistent sample so shape differences actually show up (the 2-order toy
-- seed cannot separate shapes). Populates the SAME logical content across all
-- three shapes: the relational base tables, the order_docs document collection,
-- and — automatically, since it reads the base tables — the order_dv duality view.
--
-- Idempotent: clears any prior sample first. Assumes the canonical schema exists
-- (01-canonical.sql, 02-json-collection.sql, 03-duality.sql). Run it through
-- run-sql.sh so it lands on whichever target (local container / wallet / easy).
--
-- Substitutions (all optional; sensible defaults):
--   &orders           number of orders          (default 5000)
--   &items_per_order  child items per order     (default 5)
--   &restaurants      restaurant pool size      (default 50)
--   &customers        customer pool size        (default 1000)
--   &menuitems        menu-item pool size       (default 200)
-- Size the sample with tooling/optimize/sizing.py before choosing &orders.
SET VERIFY OFF
SET FEEDBACK OFF
DEFINE orders = 5000
DEFINE items_per_order = 5
DEFINE restaurants = 50
DEFINE customers = 1000
DEFINE menuitems = 200

-- 1. Clear any prior sample (children/dependents first).
DELETE FROM order_item;
DELETE FROM order_docs;
DELETE FROM orders;

-- 2. Ensure the reference pools exist with known explicit ids (identity columns
--    are GENERATED BY DEFAULT, so explicit inserts are allowed). Only fill gaps.
INSERT INTO restaurant (restaurant_id, name, cuisine, city)
SELECT lvl, 'Restaurant ' || lvl, 'test', 'City ' || MOD(lvl, 20)
FROM (SELECT LEVEL lvl FROM dual CONNECT BY LEVEL <= &restaurants) x
WHERE NOT EXISTS (SELECT 1 FROM restaurant r WHERE r.restaurant_id = x.lvl);

INSERT INTO customer (customer_id, name, email)
SELECT lvl, 'Customer ' || lvl, 'cust' || lvl || '@example.test'
FROM (SELECT LEVEL lvl FROM dual CONNECT BY LEVEL <= &customers) x
WHERE NOT EXISTS (SELECT 1 FROM customer c WHERE c.customer_id = x.lvl);

INSERT INTO menu_item (menu_item_id, restaurant_id, name, price, category)
SELECT lvl, MOD(lvl, &restaurants) + 1, 'Item ' || lvl,
       5 + MOD(lvl, 40), 'cat' || MOD(lvl, 8)
FROM (SELECT LEVEL lvl FROM dual CONNECT BY LEVEL <= &menuitems) x
WHERE NOT EXISTS (SELECT 1 FROM menu_item m WHERE m.menu_item_id = x.lvl);

-- 3. Orders (explicit order_id so children can reference them deterministically).
INSERT INTO orders (order_id, customer_id, restaurant_id, total)
SELECT lvl, MOD(lvl, &customers) + 1, MOD(lvl, &restaurants) + 1, 0
FROM (SELECT LEVEL lvl FROM dual CONNECT BY LEVEL <= &orders);

-- 4. Order items: &items_per_order per order.
INSERT INTO order_item (order_id, menu_item_id, quantity, unit_price)
SELECT o.order_id,
       MOD(o.order_id * 7 + k, &menuitems) + 1,
       1 + MOD(k, 3),
       5 + MOD(o.order_id + k, 20)
FROM orders o
CROSS JOIN (SELECT LEVEL k FROM dual CONNECT BY LEVEL <= &items_per_order) g;

-- 5. Roll the item totals up onto the order (matches the toy seed's semantics).
UPDATE orders o
SET total = (SELECT NVL(SUM(i.quantity * i.unit_price), 0)
             FROM order_item i WHERE i.order_id = o.order_id);

-- 6. Project the SAME content into the document collection.
INSERT INTO order_docs (data)
SELECT JSON_OBJECT(
         '_id' VALUE o.order_id,
         'total' VALUE o.total,
         'restaurantId' VALUE o.restaurant_id,
         'customerId' VALUE o.customer_id,
         'items' VALUE (
           SELECT JSON_ARRAYAGG(
                    JSON_OBJECT('qty' VALUE i.quantity, 'price' VALUE i.unit_price))
           FROM order_item i WHERE i.order_id = o.order_id)
         RETURNING JSON)
FROM orders o;

COMMIT;

-- Report the generated volume across shapes (should all agree on order count).
SELECT (SELECT COUNT(*) FROM orders)     AS orders_rel,
       (SELECT COUNT(*) FROM order_docs) AS orders_doc,
       (SELECT COUNT(*) FROM order_dv)   AS orders_dv,
       (SELECT COUNT(*) FROM order_item) AS items_rel
FROM dual;
