-- Restaurant canonical domain (7-entity 3NF) — the single canonical example
-- every oracle-ai-dev skill reuses. Idempotent via 26ai-native IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS restaurant (
  restaurant_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           VARCHAR2(200 CHAR) NOT NULL,
  cuisine        VARCHAR2(80 CHAR),
  city           VARCHAR2(120 CHAR)
);

CREATE TABLE IF NOT EXISTS menu_item (
  menu_item_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id  NUMBER NOT NULL REFERENCES restaurant (restaurant_id),
  name           VARCHAR2(200 CHAR) NOT NULL,
  price          NUMBER(8, 2) NOT NULL,
  category       VARCHAR2(80 CHAR)
);

CREATE TABLE IF NOT EXISTS customer (
  customer_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           VARCHAR2(200 CHAR) NOT NULL,
  email          VARCHAR2(320 CHAR) UNIQUE
);

CREATE TABLE IF NOT EXISTS address (
  address_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    NUMBER NOT NULL REFERENCES customer (customer_id),
  line1          VARCHAR2(200 CHAR) NOT NULL,
  city           VARCHAR2(120 CHAR),
  postal_code    VARCHAR2(20 CHAR)
);

CREATE TABLE IF NOT EXISTS orders (
  order_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    NUMBER NOT NULL REFERENCES customer (customer_id),
  restaurant_id  NUMBER NOT NULL REFERENCES restaurant (restaurant_id),
  ordered_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  total          NUMBER(10, 2)
);

CREATE TABLE IF NOT EXISTS order_item (
  order_item_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       NUMBER NOT NULL REFERENCES orders (order_id),
  menu_item_id   NUMBER NOT NULL REFERENCES menu_item (menu_item_id),
  quantity       NUMBER(5) DEFAULT 1 NOT NULL,
  unit_price     NUMBER(8, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS review (
  review_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id  NUMBER NOT NULL REFERENCES restaurant (restaurant_id),
  customer_id    NUMBER NOT NULL REFERENCES customer (customer_id),
  rating         NUMBER(1) NOT NULL,
  body           VARCHAR2(2000 CHAR)
);
