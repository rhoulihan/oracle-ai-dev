CREATE TABLE IF NOT EXISTS patients (
  patient_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  outpatient_yn VARCHAR2(4000),
  hospital_number VARCHAR2(4000),
  nhs_number VARCHAR2(4000),
  gender VARCHAR2(4000),
  date_of_birth TIMESTAMP,
  patient_first_name VARCHAR2(4000),
  patient_middle_name VARCHAR2(4000),
  patient_last_name VARCHAR2(4000),
  height NUMBER,
  weight NUMBER,
  next_of_kin VARCHAR2(4000),
  home_phone VARCHAR2(4000),
  work_phone VARCHAR2(4000),
  cell_mobile_phone VARCHAR2(4000),
  other_patient_details VARCHAR2(4000)
);

CREATE TABLE IF NOT EXISTS addresses (
  address_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_1_number_building VARCHAR2(4000),
  line_2_number_street VARCHAR2(4000),
  line_3_area_locality VARCHAR2(4000),
  city VARCHAR2(4000),
  zip_postcode VARCHAR2(4000),
  state_province_county VARCHAR2(4000),
  country VARCHAR2(4000)
);

CREATE TABLE IF NOT EXISTS patient_addresses (
  patient_id NUMBER,
  address_id NUMBER,
  date_address_from TIMESTAMP,
  date_address_to TIMESTAMP,
  CONSTRAINT patient_addresses_pk PRIMARY KEY (patient_id, address_id)
);

CREATE TABLE IF NOT EXISTS patient_payment_methods (
  patient_method_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id NUMBER,
  payment_method_code VARCHAR2(4000),
  payment_method_details VARCHAR2(4000)
);

CREATE TABLE IF NOT EXISTS patient_rooms (
  stay_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id NUMBER,
  room_id VARCHAR2(20),
  date_stay_from TIMESTAMP,
  date_stay_to TIMESTAMP
);

CREATE TABLE IF NOT EXISTS patient_bills (
  patient_bill_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id NUMBER,
  date_bill_paid TIMESTAMP,
  total_amount_due NUMBER,
  other_bill_details VARCHAR2(4000)
);

CREATE TABLE IF NOT EXISTS patient_bill_items (
  patient_bill_id NUMBER,
  item_seq_nr NUMBER,
  quantity NUMBER,
  total_cost NUMBER,
  CONSTRAINT patient_bill_items_pk PRIMARY KEY (patient_bill_id, item_seq_nr)
);

CREATE TABLE IF NOT EXISTS patient_records (
  patient_record_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id NUMBER,
  billable_item_code VARCHAR2(4000),
  component_code VARCHAR2(20),
  updated_by_staff_id NUMBER,
  updated_date TIMESTAMP,
  admission_datetime TIMESTAMP,
  medical_condition VARCHAR2(4000),
  patient_record_component_details VARCHAR2(4000)
);

CREATE TABLE IF NOT EXISTS record_components (
  component_code VARCHAR2(20) PRIMARY KEY,
  component_description VARCHAR2(4000)
);

CREATE TABLE IF NOT EXISTS staff (
  staff_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_category_code VARCHAR2(4000),
  gender VARCHAR2(4000),
  staff_job_title VARCHAR2(4000),
  staff_first_name VARCHAR2(4000),
  staff_last_name VARCHAR2(4000),
  staff_qualifications VARCHAR2(4000),
  staff_birth_date TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staff_addresses (
  staff_id NUMBER,
  address_id NUMBER,
  date_address_from TIMESTAMP,
  date_address_to TIMESTAMP,
  CONSTRAINT staff_addresses_pk PRIMARY KEY (staff_id, address_id)
);

