"""Natural (non-numeric) primary keys must honour their declared types.

Field-verified on the hotel capstone: every single-column PK rendered as
NUMBER IDENTITY regardless of declared column_types, so every FK pointing at a
code-keyed lookup table (ref_countries.country_code VARCHAR2(3), ...) failed
with ORA-02267 — blocking the relational AND duality shapes outright. Worse,
the same structural assumption typed FK properties as NUMBER downstream, so
the document lane emitted .numberOnly() over VARCHAR2 codes: NULL for every
row, a GROUP BY collapsing into one NULL bucket — wrong answers that look
fast. Classic natural-code lookups are everywhere in brownfield ERDs.
"""

from tooling.generate.ddl import generate_ddl, generate_indexes, json_returning
from tooling.generate.sql import generate_document

MODEL = {
    "entities": {
        "Country": {"table": "ref_countries", "pk": "country_code",
                    "columns": {"countryCode": "country_code", "name": "name"},
                    "column_types": {"countryCode": "VARCHAR2(3)"}},
        "Hotel": {"table": "hotels", "pk": "hotel_id",
                  "columns": {"hotelName": "hotel_name",
                              "countryCode": "country_code"}},
    },
    "relationships": [
        {"from": "Hotel", "to": "Country", "from_key": "country_code",
         "to_key": "country_code", "cardinality": "N:1"},
    ],
    "projections": {"document": {"Hotel": {"collection": "hotel_docs"}}},
}


def test_a_natural_pk_keeps_its_declared_type():
    ddl = generate_ddl(MODEL, "relational")
    assert "country_code VARCHAR2(3) PRIMARY KEY" in ddl, ddl
    assert "country_code NUMBER GENERATED" not in ddl, \
        "a VARCHAR2 code key must not become a NUMBER identity"


def test_the_fk_column_matches_the_natural_pk_type():
    # ORA-02267 is exactly this mismatch: FK column typed NUMBER pointing at a
    # VARCHAR2(3) key.
    ddl = generate_ddl(MODEL, "relational")
    assert "  country_code VARCHAR2(3)" in ddl.split("CREATE TABLE IF NOT EXISTS hotels")[1], ddl


def test_a_numeric_declared_pk_still_gets_identity():
    m = {"entities": {"O": {"table": "orders", "pk": "order_id",
                            "columns": {"orderId": "order_id"},
                            "column_types": {"orderId": "NUMBER(12)"}}},
         "relationships": [], "projections": {}}
    ddl = generate_ddl(m, "relational")
    assert "order_id NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl, ddl


def test_document_lane_types_a_code_fk_as_string_not_number():
    # The F half: the wrong-answer path. json_returning must NOT report NUMBER
    # for a property referencing a VARCHAR2 natural key, so the aggregation
    # expression is .string() — not .numberOnly(), which is NULL for every row.
    assert json_returning(MODEL, "Hotel", "countryCode") is None
    q = {"root": "Hotel", "group_by": ["Hotel.countryCode"],
         "aggregates": [{"fn": "COUNT", "ref": "*", "name": "n"}]}
    sql = generate_document(MODEL, q)
    assert "d.data.countryCode.string()" in sql, sql
    assert "numberOnly" not in sql, sql
    idx = generate_indexes(MODEL, [q], shape="document")
    assert "numberOnly" not in idx, idx
