CREATE TABLE IF NOT EXISTS booking_agents (
  agent_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_name VARCHAR2(4000),
  agent_details VARCHAR2(4000)
);
CREATE TABLE IF NOT EXISTS passengers (
  passenger_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR2(4000),
  second_name VARCHAR2(4000),
  last_name VARCHAR2(4000),
  phone_number VARCHAR2(4000),
  email_address VARCHAR2(4000),
  address_lines VARCHAR2(4000),
  city VARCHAR2(4000),
  state_province_county VARCHAR2(4000),
  country VARCHAR2(4000),
  other_passenger_details VARCHAR2(4000)
);
CREATE TABLE IF NOT EXISTS itinerary_reservations (
  reservation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id NUMBER,
  passenger_id NUMBER,
  reservation_status_code VARCHAR2(4000),
  ticket_type_code VARCHAR2(4000),
  travel_class_code VARCHAR2(4000),
  date_reservation_made TIMESTAMP,
  number_in_party VARCHAR2(4000)
);
CREATE TABLE IF NOT EXISTS payments (
  payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_status_code VARCHAR2(4000),
  payment_date TIMESTAMP,
  payment_amount NUMBER
);
CREATE TABLE IF NOT EXISTS reservation_payments (
  reservation_id NUMBER,
  payment_id NUMBER,
  CONSTRAINT reservation_payments_pk PRIMARY KEY (reservation_id, payment_id)
);
CREATE TABLE IF NOT EXISTS airports (
  airport_code VARCHAR2(10) PRIMARY KEY,
  airport_name VARCHAR2(4000),
  airport_location VARCHAR2(4000),
  other_details VARCHAR2(4000)
);
CREATE TABLE IF NOT EXISTS flight_schedules (
  flight_number VARCHAR2(20) PRIMARY KEY,
  airline_code VARCHAR2(4000),
  usual_aircraft_type_code VARCHAR2(4000),
  origin_airport_code VARCHAR2(10),
  destination_airport_code VARCHAR2(4000),
  departure_date_time TIMESTAMP,
  arrival_date_time TIMESTAMP
);
CREATE TABLE IF NOT EXISTS legs (
  leg_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_number VARCHAR2(20),
  origin_airport_code VARCHAR2(4000),
  destination_airport_code VARCHAR2(4000),
  actual_departure_time TIMESTAMP,
  actual_arrival_time TIMESTAMP
);
CREATE TABLE IF NOT EXISTS itinerary_legs (
  reservation_id NUMBER,
  leg_id NUMBER,
  CONSTRAINT itinerary_legs_pk PRIMARY KEY (reservation_id, leg_id)
);
CREATE TABLE IF NOT EXISTS ref_calendar (
  day_date DATE PRIMARY KEY,
  day_number VARCHAR2(4000),
  business_day_yn VARCHAR2(4000)
);
CREATE TABLE IF NOT EXISTS flight_costs (
  flight_number VARCHAR2(20),
  aircraft_type_code VARCHAR2(20),
  valid_from_date DATE,
  valid_to_date DATE,
  flight_cost NUMBER,
  CONSTRAINT flight_costs_pk PRIMARY KEY (flight_number, aircraft_type_code, valid_from_date)
);
